#!/usr/bin/env bash
# Static analysis for this project.
# Usage: scripts/check.sh [--staged] [--strict]
#   (default)  full run: all files, types, tests, dependency audits. Use in CI, before
#              releases and before declaring work done.
#   --staged   pre-commit run: staged files only, offline, a few seconds.
#   --strict   missing tools count as failures instead of being skipped.
set -euo pipefail

# SCRIPTS: where the tooling lives. ROOT: the repository it works on; PROJECT_ROOT lets
# another repository (e.g. the scaffold itself) reuse these scripts.
SCRIPTS="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${PROJECT_ROOT:-$(cd "$SCRIPTS/.." && pwd)}"
# shellcheck source=SCRIPTDIR/lib.sh
source "$SCRIPTS/lib.sh"

MODE=full
for arg in "$@"; do
  case "$arg" in
    --staged) MODE=staged ;;
    --strict) STRICT=1 ;;
    --record-baseline) GATE_RECORD=1 ;; # adoption: record the current violations as the baseline (REQ-068)
    *) die "unknown option: $arg (usage: scripts/check.sh [--staged] [--strict])" ;;
  esac
done
if [ "$MODE" = "full" ]; then refuse_nested_run check.sh; fi
cd "$ROOT"
layout_init "$ROOT"
JUDGE_BY_MODE=1 # the findings of the tools are judged by the mode and the baseline (REQ-068)

# check_project_files: requirements, docs structure, traceability (cheap, always run).
check_project_files() {
  run_tool "requirements format" "$SCRIPTS/check-requirements.sh"
  run_tool "documentation structure" "$SCRIPTS/check-docs.sh"
  run_tool "requirement traceability" "$SCRIPTS/check-traceability.sh"
  run_tool "deferred work rows complete" "$SCRIPTS/check-deferred-work.sh"
  # Date-dependent: full run only, so a commit's hook result does not change with the day.
  if [ "$MODE" = "full" ]; then run_tool "security exceptions not expired" "$SCRIPTS/check-security-exceptions.sh"; fi
}

# check_rules_current: xaden/RULES.md must be what the pinned Xaden version generates (REQ-071).
check_rules_current() {
  local pinned conf="$TEAM_DIR/$CONF_NAME"
  pinned="$(conf_get "$conf" version)"
  if [ "$pinned" != "$(tr -d '[:space:]' <"$TOOLS_DIR/../VERSION")" ]; then
    warn "this is Xaden $(tr -d '[:space:]' <"$TOOLS_DIR/../VERSION"), the project pins $pinned; run: xaden core doctor"
    FAILURES=$((FAILURES + 1))
  elif ! render_rules | cmp -s - "$RULES_FILE"; then
    warn "xaden/RULES.md does not match Xaden $pinned (edited by hand, or generated by another version); run: xaden project rules"
    FAILURES=$((FAILURES + 1))
  fi
}

# detected_kinds: the kinds of checks the project's stack calls for, from the files it has.
detected_kinds() {
  if [ -f pyproject.toml ] || [ -f setup.py ] || ls requirements*.txt >/dev/null 2>&1; then printf 'test lint typecheck'
  elif [ -f package.json ]; then printf 'test lint'
  fi
}

# check_findings_status_config: "findings-status.<name> = 1,2" (REQ-101) names a mapped or built-in
# check other than "test" and lists exit statuses from 1 to 255; anything else is a mistake that
# would silently turn a crash into a finding, so it stops the run.
check_findings_status_config() {
  local conf="$TEAM_DIR/$CONF_NAME" key name value status
  while IFS= read -r key; do
    name="${key#findings-status.}"
    value="$(conf_get "$conf" "$key")"
    [ "$name" != "test" ] || die "xaden.conf: $key is not allowed; failing assertions are never baselined"
    if [ -z "$(conf_get "$conf" "check.$name")" ] && ! printf ' shellcheck semgrep actionlint zizmor ' | grep -q " $name "; then
      die "xaden.conf: $key names no check (check.$name is not mapped)"
    fi
    printf '%s' "$value" | grep -Eq '^[0-9]{1,3}(,[0-9]{1,3})*$' || die "xaden.conf: $key = '$value' is not a comma separated list of exit statuses from 1 to 255"
    for status in ${value//,/ }; do
      if [ $((10#$status)) -lt 1 ] || [ $((10#$status)) -gt 255 ]; then die "xaden.conf: $key lists $status; exit statuses run from 1 to 255"; fi
    done
  done < <(conf_keys "$conf" "findings-status.")
}

# check_settings_unchanged: a pull request must not judge itself (REQ-137). In a pull request run, a change to
# the settings that decide how the project is checked stops the run before any mapped command executes.
SETTINGS_BLOCKED=0
check_settings_unchanged() {
  [ "$MODE" = "full" ] && [ -f "$TEAM_DIR/$CONF_NAME" ] || return 0
  info "check settings unchanged from the merge base"
  if "$SCRIPTS/check-settings.sh"; then
    CHECKS_PASSED=$((CHECKS_PASSED + 1))
  else
    FAILURES=$((FAILURES + 1))
    SETTINGS_BLOCKED=1
  fi
}

# staged_command_confirmed <key> <command>: a mapped command that differs from the one the last commit had
# runs in pre-commit only after a yes (REQ-137): the line is code that executes on this machine. Without a
# terminal it does not run.
staged_command_confirmed() {
  local committed_conf committed
  committed_conf="$(mktemp)"
  if ! git -C "$GIT_REPO" show "HEAD:$TEAM_DIR_NAME/$CONF_NAME" >"$committed_conf" 2>/dev/null; then rm -f "$committed_conf"; return 0; fi
  committed="$(conf_get "$committed_conf" "$1")"
  rm -f "$committed_conf"
  [ "$committed" != "$2" ] || return 0
  warn "$1 changed in the staged xaden.conf and would run on this machine: $2" >&2
  has_terminal || { warn "No terminal, so it did not run; 'xaden check' runs it after you read the line." >&2; return 1; }
  ask "Run the changed command $1 now?" || { warn "Skipped $1." >&2; return 1; }
}

# check_mapped_commands: the commands the team mapped in xaden.conf ("check.<name> = <command>",
# REQ-069) run under the project's mode and baseline. Pre-commit runs only the kinds named in
# "hook-checks" (default: lint); the full run runs all. Expected kinds without a command are gaps:
# a warning, an error in strict mode.
check_mapped_commands() {
  [ "$SETTINGS_BLOCKED" = 0 ] || return 0
  local conf="$TEAM_DIR/$CONF_NAME" key name kind hooked mode command_line binary expected network_note
  hooked="$(conf_get "$conf" hook-checks lint)"
  mode="$(project_mode "$ROOT")"
  check_findings_status_config
  while IFS= read -r key; do
    name="${key#check.}"
    printf '%s' "$name" | grep -Eq '^[a-z][a-z0-9-]*$' || die "xaden.conf: invalid check name '$name'"
    if [ "$MODE" = "staged" ] && ! printf ',%s,' "$hooked" | grep -q ",$name,"; then continue; fi
    command_line="$(conf_get "$conf" "$key")"
    binary="${command_line%% *}"
    network_note=""
    [ "$name" != audit ] || network_note=" (needs the network)"
    if [ "$MODE" = "staged" ] && ! staged_command_confirmed "$key" "$command_line"; then continue; fi
    if ! has_command "$binary"; then record_missing_tool "check: $name" "$binary"; continue; fi
    # the audits ask a vulnerability database: without a network they fail with the tool's own message (REQ-106)
    gate_run "$name" "check: $name${network_note}" bash -c "$command_line"
  done < <(conf_keys "$conf" "check.")
  [ "$MODE" = "full" ] || return 0
  if [ "$(conf_get "$conf" commit-convention conventional)" = other ]; then
    tip "commit-convention is 'other', so the Refs: checks only advise; set commit-convention = conventional in xaden/xaden.conf to enforce them"
  fi
  expected="$(conf_get "$conf" expect)"
  # No "expect" line (a project that began empty): the stack that appeared decides.
  if [ -z "$expected" ] && ! grep -q '^expect' "$conf"; then expected="$(detected_kinds | tr ' ' ',')"; fi
  for kind in $(printf '%s' "$expected" | tr ',' ' '); do
    [ -z "$(conf_get "$conf" "check.$kind")" ] || continue
    if [ "$mode" = "strict" ]; then
      warn "gap: no '$kind' check is configured (check.$kind in xaden/xaden.conf)"
      FAILURES=$((FAILURES + 1))
    else
      warn "gap: no '$kind' check is configured (check.$kind in xaden/xaden.conf; mode $mode)"
    fi
  done
  report_not_covered
}

# known_extra_checks: "<kind> <tool>" lines for the checks Xaden knows for the stack's files, beyond test, lint
# and typecheck (REQ-105). Keep in step with xaden project add-preset.
known_extra_checks() {
  if [ -f pyproject.toml ] || [ -f setup.py ] || ls requirements*.txt >/dev/null 2>&1; then
    printf '%s\n' "audit pip-audit" "security bandit"
  elif [ -f package.json ]; then
    printf '%s\n' "audit npm audit"
  fi
}

# report_not_covered: a full run says which checks Xaden knows for this stack and nothing maps. An expected kind is already a gap (REQ-101), so it is skipped here.
report_not_covered() {
  local conf="$TEAM_DIR/$CONF_NAME" kind tool printed=""
  while read -r kind tool; do
    [ -n "$kind" ] || continue
    [ -z "$(conf_get "$conf" "check.$kind")" ] || continue
    if printf ',%s,' "$(conf_get "$conf" expect)" | grep -q ",$kind,"; then continue; fi
    printf 'NOT COVERED: %s; Xaden knows it for this stack. Map it with check.%s in xaden/xaden.conf (see "What Xaden checks")\n' "$tool" "$kind"
    printed=1
  done < <(known_extra_checks)
  # a project adopted before REQ-106 keeps its expect line; nothing turns red by an upgrade
  [ -z "$printed" ] || tip "name them in 'expect' once they are mapped (xaden project add-preset <stack> maps the commands) so a missing mapping is a gap"
}

# check_stacks: a project runs its own commands (REQ-069); stacks/common.sh checks the workflows.
check_stacks() {
  # shellcheck disable=SC1091 # discovered at runtime
  source "$SCRIPTS/stacks/common.sh"
  stack_check "$MODE"
  check_mapped_commands
}

# show_tips: optional tools that fit this project (REQ-051); full run only, result unchanged.
show_tips() {
  # shellcheck disable=SC1091 # discovered at runtime
  source "$SCRIPTS/stacks/common.sh"
  stack_tips
}

if [ "$MODE" = "staged" ]; then
  enter_staged_snapshot "$ROOT" # checks see exactly the staged content (REQ-020)
  # Xaden's own files present but untracked (a foreign repository): read them from the working tree.
  if [ ! -e "$SNAPSHOT/$TEAM_DIR_NAME/$CONF_NAME" ] && [ -f "$GIT_REPO/$TEAM_DIR_NAME/$CONF_NAME" ]; then
    ln -s "$GIT_REPO/$TEAM_DIR_NAME" "$SNAPSHOT/$TEAM_DIR_NAME"
  fi
  ROOT="$SNAPSHOT"
  layout_init "$ROOT"
fi

info "check mode: $MODE"
check_rules_current
check_project_files
lint_shell "$MODE"
scan_secrets "$MODE"
scan_sast "$MODE" "$TOOLS_DIR/.semgrep"
check_settings_unchanged
check_stacks
if [ "$MODE" = "full" ]; then show_tips; fi

if [ "${GATE_RECORD:-0}" = "1" ]; then
  ok "baselines recorded in xaden/baselines/"
  exit 0
fi
finish_checks
