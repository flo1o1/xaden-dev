#!/usr/bin/env bash
# Converts the old requirements table (docs/requirements/REQUIREMENTS.md) into one file per
# requirement (REQ-048). Every row becomes docs/requirements/<epic>/REQ-nnn-<slug>.md with its
# ID, status, priority, date, text (as title) and acceptance criteria unchanged; the job story
# is left as TODO for a human to write. The table's change log moves to README.md, INDEX.md
# is generated and the table file is removed from the working tree. Nothing is committed.
# Usage: scripts/migrate-requirements.sh [epic]   (default epic: unsorted)
set -euo pipefail

# SCRIPTS: where the tooling lives. ROOT: the repository it works on; PROJECT_ROOT lets
# another repository (e.g. the scaffold itself) reuse these scripts.
SCRIPTS="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${PROJECT_ROOT:-$(cd "$SCRIPTS/.." && pwd)}"
# shellcheck source=SCRIPTDIR/lib.sh
source "$SCRIPTS/lib.sh"
# shellcheck source=SCRIPTDIR/requirements-lib.sh
source "$SCRIPTS/requirements-lib.sh"

DIR="$ROOT/docs/requirements"
TABLE="$DIR/REQUIREMENTS.md"
EPIC="${1:-unsorted}"
TODAY="$(date +%Y-%m-%d)"
TODO_JOB='TODO: rewrite as "When <situation>, I want to <motivation>, so I can <expected outcome>.", or change the type to quality and use a "## Quality goal" section.'

# table_rows: tab-separated id, text, priority, status, acceptance, date for every table row.
table_rows() {
  awk -F'|' '
    function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
    /^\| *REQ-/ { printf "%s\t%s\t%s\t%s\t%s\t%s\n", trim($2), trim($3), trim($4), trim($5), trim($6), trim($7) }
  ' "$TABLE"
}

# project_title: the name from the table heading "# Requirements — <name>", if any.
project_title() {
  sed -n 's/^# Requirements[^A-Za-z0-9]*//p' "$TABLE" | head -n 1
}

# change_log: the list under "## Change log" in the table file.
change_log() {
  awk '/^## Change log/ { inside = 1; next } inside && /^## / { exit } inside && /^- / { print }' "$TABLE"
}

# write_readme: README.md with the migrated change log and a migration entry.
write_readme() {
  local name
  name="$(project_title)"
  {
    printf '# Requirements%s\n\n' "${name:+ — $name}"
    printf 'One file per requirement, grouped in epic folders; format and rules: AGENTS.md §2.\n'
    printf 'Overview: INDEX.md (generated by scripts/req.sh index). New requirement:\n'
    printf 'scripts/req.sh new <epic> <job|quality> "<title>".\n\n## Change log\n\n'
    change_log
    printf -- '- %s Requirements migrated to one file per requirement (scripts/migrate-requirements.sh).\n' "$TODAY"
  } >"$DIR/README.md"
}

# validate_ids: dies before anything is written if a row's ID is not REQ-nnn. The ID becomes
# part of a file path, and the table is project content (security review 2026-10-11-audit-fixes #1).
validate_ids() {
  local id
  while IFS= read -r id; do
    printf '%s' "$id" | grep -Eq '^REQ-[0-9]{3,}$' || die "invalid requirement ID in the table: $id"
  done < <(table_rows | cut -f1)
}

# migrate_rows: writes one requirement file per table row.
migrate_rows() {
  local id text priority status acceptance updated count=0
  while IFS="$(printf '\t')" read -r id text priority status acceptance updated; do
    write_requirement "$DIR/$EPIC/$id-$(slugify "$text").md" "$id" job "$EPIC" "$priority" \
      "$status" "$updated" "$text" "$TODO_JOB" "$acceptance"
    count=$((count + 1))
  done < <(table_rows)
  info "migrated $count requirement(s) into docs/requirements/$EPIC/"
}

main() {
  [ -f "$TABLE" ] || die "no requirements table at docs/requirements/REQUIREMENTS.md"
  is_epic_name "$EPIC" || die "epic must be lowercase words with dashes: $EPIC"
  [ -z "$(requirement_files "$DIR")" ] || die "requirement files already exist; nothing migrated"
  [ -e "$DIR/README.md" ] && die "docs/requirements/README.md already exists; nothing migrated"
  [ -n "$(table_rows)" ] || die "the table has no requirement rows"
  validate_ids
  write_epic "$DIR/$EPIC" "Unsorted" \
    "TODO: Requirements migrated from the old table. Move each one into a topic epic (folder and \`epic:\` field) and describe that epic's goal as a job."
  migrate_rows
  write_readme
  rm "$TABLE"
  render_index "$DIR" >"$DIR/$INDEX_FILE"
  render_index "$DIR" full >"$DIR/$INDEX_FULL_FILE"
  info "next: rewrite each TODO job story, sort requirements into epics, run scripts/req.sh index"
  info "and scripts/check-requirements.sh, then commit docs/requirements/"
}

main
