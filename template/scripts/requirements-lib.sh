#!/usr/bin/env bash
# Reading and writing requirement files (REQ-046, REQ-047). Source it after lib.sh.
# Layout: docs/requirements/<epic>/EPIC.md and docs/requirements/<epic>/REQ-nnn-<slug>.md.
# A requirement file starts with front matter (id, type, epic, priority, status, updated),
# then "# <title>", a "## Job" (type job) or "## Quality goal" (type quality) section and
# "## Acceptance criteria". INDEX.md is generated from the files by render_index.

# Allowed values, shared by the validator and the generator.
# shellcheck disable=SC2034 # the constants below are used by the scripts that source this file
REQUIREMENT_TYPES="job quality"
REQUIREMENT_PRIORITIES="must should could wont"
REQUIREMENT_STATUSES="draft approved in-progress done dropped"
# Name of the generated index and of the per-epic description file.
INDEX_FILE="INDEX.md"
EPIC_FILE="EPIC.md"

# is_epic_name <name>: true for an epic folder name (lowercase words joined by dashes).
is_epic_name() { printf '%s' "$1" | grep -Eq '^[a-z0-9][a-z0-9-]*$'; }

# epic_dirs <requirements-dir>: one epic folder per line, sorted.
epic_dirs() {
  find "$1" -mindepth 1 -maxdepth 1 -type d ! -name '.*' ! -name '_*' | LC_ALL=C sort
}

# requirement_files <requirements-dir>: one requirement file per line, sorted by path.
requirement_files() {
  find "$1" -mindepth 2 -maxdepth 2 -type f -name 'REQ-*.md' | LC_ALL=C sort
}

# requirement_records <requirements-dir>: one tab-separated line per requirement file:
# id, status, priority, type, epic, title, path. Fields missing in a file are empty.
# shellcheck disable=SC2016 # single-quoted awk program, not shell
requirement_records() {
  local files
  files="$(requirement_files "$1")"
  [ -n "$files" ] || return 0
  printf '%s\n' "$files" | tr '\n' '\0' | xargs -0 awk '
    function flush() {
      if (path != "") printf "%s\t%s\t%s\t%s\t%s\t%s\t%s\n", \
        field["id"], field["status"], field["priority"], field["type"], field["epic"], title, path
    }
    FNR == 1 { flush(); path = FILENAME; split("", field); title = ""; in_front = 0; after_front = 0 }
    FNR == 1 && $0 == "---" { in_front = 1; next }
    in_front && $0 == "---" { in_front = 0; after_front = 1; next }
    in_front {
      key = $0; sub(/:.*/, "", key)
      value = $0; sub(/^[^:]*:[ \t]*/, "", value); sub(/[ \t]+$/, "", value)
      field[key] = value; next
    }
    after_front && title == "" && /^# / { title = substr($0, 3) }
    END { flush() }'
}

# requirement_path <requirements-dir> <REQ-nnn>: the file of one requirement; dies if the ID is
# malformed or unknown. awk reads to the end: an early exit would break the pipe of a big project (REQ-126).
requirement_path() {
  local path
  printf '%s' "$2" | grep -Eq '^REQ-[0-9]{3,}$' || die "invalid requirement ID: $2"
  path="$(requirement_records "$1" | awk -F'\t' -v id="$2" '$1 == id && !seen { print $7; seen = 1 }')"
  [ -n "$path" ] || die "$2 does not exist in the requirements folder"
  printf '%s' "$path"
}

# epic_title <epic-dir>: the first "# " heading of EPIC.md, or the folder name.
epic_title() {
  local title=""
  [ -f "$1/$EPIC_FILE" ] && title="$(sed -n 's/^# //p' "$1/$EPIC_FILE" | head -n 1)"
  printf '%s' "${title:-$(basename "$1")}"
}

# Name of the full table nothing imports (REQ-126); INDEX.md lists only what is not finished.
INDEX_FULL_FILE="INDEX-full.md"

# render_index <requirements-dir> [full]: the content INDEX.md must have (REQ-126). It is imported
# into every session, so a requirement that is done or dropped is only counted per epic and the
# size follows the open work, not the history. With "full" every requirement is a row
# (INDEX-full.md, which no tool imports).
# shellcheck disable=SC2016 # backticks are Markdown, not command substitution
render_index() {
  local dir=$1 full=${2:-} epic records name finished open
  records="$(requirement_records "$dir" | LC_ALL=C sort)"
  printf '# Requirements index\n\n'
  printf 'Generated by `scripts/req.sh index` from the requirement files; do not edit by hand.\n'
  printf 'Read one requirement with `scripts/req.sh show REQ-nnn` (`--brief` for the goal and criteria only).\n'
  if [ -z "$full" ]; then
    printf 'Requirements that are done or dropped are only counted; `scripts/req.sh list --epic <epic> --status <status>`\n'
    printf 'lists them, and `%s` holds the full table.\n' "$INDEX_FULL_FILE"
  fi
  while IFS= read -r epic; do
    name="$(basename "$epic")"
    printf '\n## %s (`%s`)\n\n' "$(epic_title "$epic")" "$name"
    finished="$(printf '%s\n' "$records" | awk -F'\t' -v epic="$name" '$5 == epic && ($2 == "done" || $2 == "dropped") { n[$2]++ }
      END { if (n["done"]) printf "%d done", n["done"]; if (n["done"] && n["dropped"]) printf ", "; if (n["dropped"]) printf "%d dropped", n["dropped"] }')"
    if [ -z "$full" ] && [ -n "$finished" ]; then printf '%s.\n\n' "$finished"; fi
    open="$(printf '%s\n' "$records" | awk -F'\t' -v epic="$name" -v full="$full" \
      '$5 == epic && (full != "" || ($2 != "done" && $2 != "dropped")) { printf "| %s | %s | %s | %s | %s |\n", $1, $4, $3, $2, $6 }')"
    if [ -z "$open" ]; then
      [ -n "$finished" ] || printf 'No requirements yet.\n'
      continue
    fi
    printf '| ID | Type | Priority | Status | Title |\n|----|------|----------|--------|-------|\n%s\n' "$open"
  done < <(epic_dirs "$dir")
}

# SLUG_LENGTH: longest file-name slug; longer ones are cut at a word boundary.
SLUG_LENGTH=50

# slugify <text>: lowercase words joined by dashes, for file names.
slugify() {
  local slug
  slug="$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]' | sed -e 's/[^a-z0-9]\{1,\}/-/g' -e 's/^-//' -e 's/-$//')"
  if [ "${#slug}" -gt "$SLUG_LENGTH" ]; then
    slug="${slug:0:$SLUG_LENGTH}"
    slug="${slug%-*}"
  fi
  printf '%s' "$slug"
}

# next_requirement_id <requirements-dir>: the next free REQ-nnn (global across epics).
next_requirement_id() {
  local highest
  highest="$(requirement_records "$1" | cut -f1 | sed -n 's/^REQ-0*\([0-9][0-9]*\)$/\1/p' | sort -n | tail -n 1)"
  printf 'REQ-%03d' "$(( ${highest:-0} + 1 ))"
}

# write_requirement <path> <id> <type> <epic> <priority> <status> <date> <title> <statement>
#   <acceptance-criteria>: writes one requirement file. The statement goes into "## Job" or
#   "## Quality goal"; acceptance criteria are written as one list item per line.
write_requirement() {
  local path=$1 id=$2 type=$3 epic=$4 priority=$5 status=$6 date=$7 title=$8 statement=$9
  local criteria=${10} section="Job"
  [ "$type" = "quality" ] && section="Quality goal"
  {
    printf -- '---\nid: %s\ntype: %s\nepic: %s\npriority: %s\nstatus: %s\nupdated: %s\n---\n\n' \
      "$id" "$type" "$epic" "$priority" "$status" "$date"
    printf '# %s\n\n## %s\n\n%s\n\n## Acceptance criteria\n\n' "$title" "$section" "$statement"
    printf '%s\n' "$criteria" | sed 's/^/- /'
  } >"$path"
}

# write_epic <epic-dir> <title> <goal>: creates EPIC.md unless it exists.
write_epic() {
  mkdir -p "$1"
  [ -f "$1/$EPIC_FILE" ] && return 0
  printf '# %s\n\n## Goal\n\n%s\n' "$2" "$3" >"$1/$EPIC_FILE"
}
